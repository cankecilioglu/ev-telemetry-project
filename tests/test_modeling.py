def make_modelling_frame(rows_per_trip: int = 60, seed: int = 7) -> pd.DataFrame:
    """Synthetic telemetry with every column the models consume."""
    rng = np.random.default_rng(seed)
    frames = []
    for trip in (1, 2, 3):
        start = pd.Timestamp("2023-10-23 08:00:00", tz="UTC") + pd.Timedelta(days=trip)
        speed = rng.uniform(0, 100, rows_per_trip)
        accel = rng.uniform(-2, 2, rows_per_trip)
        grade = rng.uniform(-8, 8, rows_per_trip)
        air = rng.integers(0, 2, rows_per_trip)
        frame = pd.DataFrame(
            {
                config.GROUP_COL: trip,
                config.TIME_COL: start + pd.to_timedelta(np.arange(rows_per_trip) * 2, unit="s"),
                "SPD": speed,
                "accel_mps2": accel,
                "grade_pct": grade,
                "ACC": rng.uniform(0, 80, rows_per_trip),
                "BRK": rng.uniform(0, 30, rows_per_trip),
                "ECO_bin": 0.0,
                "AIR_bin": air.astype(float),
            }
        )
        # Target generated by the physics basis with known coefficients, plus noise.
        design = build_physics_design(frame)
        beta_true = np.array([1.8e3, 0.40, 5.0e3, 120.0, 2.0e3, 1.2e3])
        no_noise = design[PHYSICS_FEATURES].to_numpy() @ beta_true
        frame[config.TARGET] = no_noise + rng.normal(0, 0.5, rows_per_trip)
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def test_per_trip_split_holds_out_rows_from_every_trip():
    frame = make_modelling_frame(rows_per_trip=50)

    split = per_trip_split(frame, test_fraction=0.2)

    assert set(split.test[config.GROUP_COL]) == {1, 2, 3}
    assert set(split.train[config.GROUP_COL]) == {1, 2, 3}
    for trip, group in split.test.groupby(config.GROUP_COL):
        assert len(group) == 10
    # Within every trip the held-out block is strictly later than the train block.
    for trip in (1, 2, 3):
        train_max = split.train.loc[split.train[config.GROUP_COL] == trip, config.TIME_COL].max()
        test_min = split.test.loc[split.test[config.GROUP_COL] == trip, config.TIME_COL].min()
        assert train_max < test_min


def test_physics_calibration_recovers_known_coefficients():
    frame = make_modelling_frame(rows_per_trip=200, seed=11)

    calibration = fit_physics_calibration(frame)

    beta_true = np.array([1.8e3, 0.40, 5.0e3, 120.0, 2.0e3, 1.2e3])
    np.testing.assert_allclose(calibration.beta, beta_true, rtol=0.05)
    assert calibration.n_fit_rows == len(frame)


def test_evaluate_models_returns_one_row_per_method():
    frame = make_modelling_frame()
    split = chronological_split(frame, test_fraction=0.2)

    metrics, predictions, extras = evaluate_models(split, tune_rf=False)

    assert list(metrics["key"]) == ["baseline", "linear", "physics", "rf"]
    assert (metrics["n_test"] == len(split.test)).all()
    assert len(predictions) == len(split.test)
    assert predictions["rf"].notna().all()
    assert extras["calibration"].n_fit_rows == len(split.train)
    # On synthetic data generated by the physics equation the calibrated model
    # must beat the training mean.
    mae = metrics.set_index("key")["MAE_A"]
    assert mae["physics"] < mae["baseline"]


def test_add_operating_regime_labels_speed_grade_and_pedals():
    frame = pd.DataFrame(
        {
            "SPD": [10.0, 50.0, 90.0],
            "grade_pct": [-5.0, 0.0, 5.0],
            "ACC": [20.0, 0.0, 0.0],
            "BRK": [0.0, 15.0, 0.0],
        }
    )

    labelled = add_operating_regime(frame)

    assert labelled["speed_band"].astype(str).tolist() == ["0-20", "40-60", "80-100"]
    assert labelled["grade_band"].astype(str).tolist() == ["downhill", "flat", "uphill"]
    assert labelled["regime"].tolist() == ["accelerating", "braking", "coasting"]


def test_error_table_reports_mae_and_bias_per_category():
    predictions = pd.DataFrame(
        {
            "speed_band": pd.Categorical(["0-20", "0-20", "80-100"]),
            "y_true": [10.0, 20.0, 30.0],
            "baseline": [12.0, 18.0, 60.0],
            "rf": [10.0, 21.0, 30.0],
        }
    )

    table = error_table(predictions, by="speed_band", methods=("baseline", "rf"))

    assert set(table["method"]) == {"baseline", "rf"}
    slow = table[(table["speed_band"] == "0-20") & (table["method"] == "baseline")].iloc[0]
    assert slow["n"] == 2
    assert slow["MAE_A"] == pytest.approx(2.0)
    assert slow["bias_A"] == pytest.approx(0.0)
    fast_rf = table[(table["speed_band"] == "80-100") & (table["method"] == "rf")].iloc[0]
    assert fast_rf["MAE_A"] == pytest.approx(0.0)
