"""Unit tests for the time-ordered split, baseline and metrics."""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from src import config
from src.features import PHYSICS_FEATURES, build_physics_design
from src.modeling import (
    add_operating_regime,
    baseline_predict,
    chronological_split,
    error_table,
    evaluate_models,
    fit_physics_calibration,
    per_trip_split,
    regression_metrics,
    split_composition,
)


def make_series_frame(rows: int = 100) -> pd.DataFrame:
    """Monotonic timestamps split between two trips."""
    stamps = pd.date_range("2023-10-23 08:00:00", periods=rows, freq="2s", tz="UTC")
    return pd.DataFrame(
        {
            "COND": np.where(np.arange(rows) < rows // 2, 1, 2),
            "timestamp": stamps,
            config.TARGET: np.arange(rows, dtype=float),
        }
    )


def test_split_keeps_chronology_and_sizes():
    frame = make_series_frame(100)

    split = chronological_split(frame, test_fraction=0.2)

    assert len(split.train) == 80
    assert len(split.test) == 20
    assert split.train[config.TIME_COL].max() < split.test[config.TIME_COL].min()


def test_split_does_not_shuffle_when_input_is_shuffled():
    frame = make_series_frame(100).sample(frac=1.0, random_state=3)

    split = chronological_split(frame, test_fraction=0.2)

    ordered = frame.sort_values(config.TIME_COL)
    assert split.test[config.TIME_COL].min() == ordered[config.TIME_COL].iloc[80]
    assert split.train[config.TIME_COL].max() == ordered[config.TIME_COL].iloc[79]


def test_split_rejects_invalid_fraction():
    frame = make_series_frame(20)
    with pytest.raises(ValueError):
        chronological_split(frame, test_fraction=1.5)


def test_baseline_predicts_training_mean():
    train = pd.DataFrame({config.TARGET: [10.0, 20.0, 30.0]})
    test = pd.DataFrame({config.TARGET: [0.0, 100.0]})

    predictions = baseline_predict(train, test)

    assert predictions.tolist() == [20.0, 20.0]


def test_regression_metrics_are_in_target_units():
    y_true = np.array([10.0, 20.0])
    y_pred = np.array([12.0, 16.0])

    metrics = regression_metrics(y_true, y_pred)

    assert metrics["MAE"] == pytest.approx(3.0)
    assert metrics["bias"] == pytest.approx(-1.0)
    assert metrics["RMSE"] == pytest.approx(np.sqrt(10.0))


def test_split_composition_counts_every_row():
    split = chronological_split(make_series_frame(100), test_fraction=0.2)

    table = split_composition(split)
    totals = table.loc[table["COND"] == "total"].iloc[0]

    assert totals["train_rows"] == 80
    assert totals["test_rows"] == 20


